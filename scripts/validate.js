// Checks the pull engine against the exact maths and the publishers' numbers with a very large
// number of pulls, then writes docs/VALIDATION.md.  Run: node scripts/validate.js

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { testRules, pityMoments, featuredShareTheory, fiftyFiftyTheory } from '../src/engine.js';
import { PRESETS } from '../src/presets.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const FIVES = Number(process.env.FIVES || 1000000);

// Standard normal tail and a chi-square p-value (Wilson-Hilferty), good to about 3 decimals.
function normalTail(z) {
  const t = 1 / (1 + 0.2316419 * Math.abs(z));
  const d = 0.3989423 * Math.exp((-z * z) / 2);
  const p = d * t * (0.3193815 + t * (-0.3565638 + t * (1.781478 + t * (-1.821256 + t * 1.330274))));
  return z > 0 ? p : 1 - p;
}
function chiSquareP(x, k) {
  const z = ((x / k) ** (1 / 3) - (1 - 2 / (9 * k))) / Math.sqrt(2 / (9 * k));
  return normalTail(z);
}

function check(name, rules, published) {
  const t0 = Date.now();
  const r = testRules(rules, FIVES, 'validate');
  const ms = Date.now() - t0;
  const { dist, mean, sd } = pityMoments(rules);
  const share = featuredShareTheory(rules);
  const se = sd / Math.sqrt(r.fives);
  // goodness of fit of where the 5★s landed, merging buckets with fewer than 5 expected
  let chi = 0;
  let df = -1;
  let accObs = 0;
  let accExp = 0;
  for (let n = 1; n < dist.length; n++) {
    accObs += r.landed[n];
    accExp += dist[n] * r.fives;
    if (accExp >= 5) {
      chi += (accObs - accExp) ** 2 / accExp;
      df += 1;
      accObs = 0;
      accExp = 0;
    }
  }
  if (accExp > 0) chi += (accObs - accExp) ** 2 / Math.max(accExp, 1e-9);
  const p = chiSquareP(chi, Math.max(1, df));
  const z = (r.meanPity - mean) / se;
  // A share of exactly 0 or 1 has no spread: it either matches or it doesn't.
  const zOf = (seen, p, n) => (p > 0 && p < 1 ? (seen - p) / Math.sqrt((p * (1 - p)) / n) : Math.abs(seen - p) < 1e-12 ? 0 : Infinity);
  const zShare = zOf(r.featuredShare, share, r.fives);
  const q = rules.featuredChance;
  const plain = r.count.WON + r.count.LOST;
  const zWon = plain ? zOf(r.wonShare, q, plain) : 0;
  const w = fiftyFiftyTheory(rules);
  const zRad = rules.radiance?.on ? (r.winWithRadiance - w) / Math.sqrt((w * (1 - w)) / r.attempts) : 0;
  return { name, rules, published, r, ms, mean, share, w, z, zShare, zWon, zRad, chi, df, p, hard: dist[rules.hardPity] };
}

const pct = (x, d = 3) => `${(x * 100).toFixed(d)}%`;
const runs = [];
for (const preset of PRESETS) if (preset.rules) runs.push(check(preset.name, preset.rules, preset.published));
const base = PRESETS[0].rules;
runs.push(check('Character banner without soft pity (flat 0.6% to pull 90)', { ...base, softPityStart: 999, softPityStep: 0, radiance: { ...base.radiance, on: false } }, null));
runs.push(check('Character banner without the guarantee or Radiance', { ...base, guarantee: false, radiance: { ...base.radiance, on: false } }, null));

let md = `# Gacha Lab validation

Generated by \`node scripts/validate.js\` on ${new Date().toISOString().slice(0, 10)}. Each rule set is pulled until it has given
**${FIVES.toLocaleString('en-US')} 5★s**, on one banner state the way a single account pulls, separate from any player
behaviour. "z" is how many standard errors the result sits from the exact maths; anything inside ±4 is a match.
The landing test is a chi-square goodness of fit of the pull each 5★ landed on against the exact distribution.

| Rule set | 5★ rate: test / exact / published | Featured per pull: test / exact / published | Pulls per 5★ (z) | Featured share (z) | 50/50 won (z) | With Radiance (z) | Longest wait | Landing test |
|---|---|---|---|---|---|---|---|---|
`;
const pub = (x, d) => (x ? `${parseFloat((x * 100).toFixed(d))}%` : '–');
for (const v of runs) {
  const fpp = v.r.featured / v.r.pulls;
  md += `| ${v.name} | ${pct(v.r.rate)} / ${pct(1 / v.mean)} / ${pub(v.published?.rate, 3)} | ${pct(fpp)} / ${pct(v.share / v.mean)} / ${pub(v.published?.featuredRate, 3)} | ${v.r.meanPity.toFixed(3)} vs ${v.mean.toFixed(3)} (${v.z.toFixed(2)}) | ${pct(v.r.featuredShare, 2)} vs ${pct(v.share, 2)} (${v.zShare.toFixed(2)}) | ${pct(v.r.wonShare, 2)} vs ${pct(v.rules.featuredChance, 2)} (${v.zWon.toFixed(2)}) | ${v.rules.radiance?.on ? `${pct(v.r.winWithRadiance, 2)} vs ${pct(v.w, 2)} (${v.zRad.toFixed(2)}); 55% published` : '–'} | ${v.r.longest} of ${v.rules.hardPity} | χ²=${v.chi.toFixed(1)}, df ${v.df}, p=${v.p.toFixed(3)} |\n`;
}
md += `
## What each column shows

- **5★ rate**: 5★s divided by pulls. Publishers call this the consolidated or overall rate (HoYoverse: "consolidated
  probability (including guarantee)"). The published column shows it where one exists; PGR's is Kuro's figure for
  the standard pool, and Love and Deepspace's the wiki's transcription.
- **Pulls per 5★**: the average pity a 5★ lands on. The soft-pity model gives exactly ${runs[0].mean.toFixed(3)} for the character banner.
- **Featured share**: share of 5★s that were the featured unit. With a 50/50 and a guarantee after each loss it is exactly 2/3.
- **50/50 won**: share of non-guaranteed 5★s that won the 50/50 outright, with Capturing Radiance set aside
  (HoYoverse's "50.000% … excluding the triggering of Capturing Radiance").
- **With Radiance**: Genshin only. The rules HoYoverse discloses (a 3% trigger, certain after three losses in a
  row) give 54.5%; HoYoverse publishes 55%. The half point is not explained by anything published.
- **Featured per pull**: featured units per pull. HoYoverse publishes it as the consolidated rate for the
  promotional character (1.103% Genshin, 1.113% Star Rail, 1.067% Zenless Zone Zero); their figures are worked
  from the rounded 1.6%, ours from the model's 1.6052%.
- **Longest wait**: the most pulls any 5★ took. It can never pass hard pity. (999 means no hard pity.)
- Sparks and free copies sit on top of these rules and aren't part of this test; the engine tests check them.
- **Landing test**: a p-value above 0.001 means the landing pattern is what the rules predict.

Run times: ${runs.map((v) => `${v.name} ${(v.ms / 1000).toFixed(1)} s`).join('; ')}.
`;
writeFileSync(resolve(root, 'docs/VALIDATION.md'), md);
console.log(md);
const bad = runs.filter((v) => Math.abs(v.z) > 4 || Math.abs(v.zShare) > 4 || Math.abs(v.zWon) > 4 || Math.abs(v.zRad) > 4 || v.r.longest > v.rules.hardPity || v.p < 0.001);
if (bad.length) {
  console.error(`FAILED: ${bad.map((v) => v.name).join(', ')}`);
  process.exit(1);
}
